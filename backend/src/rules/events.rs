/// The supported trigger vocabulary. Serialized names match the activity
/// event vocabulary (`activity::events`) so operational queries can correlate
/// the two histories.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum TriggerType {
    TaskStatusChanged,
    TaskPriorityChanged,
    TaskAssigned,
}

impl TriggerType {
    /// Parse the serialized trigger name (API input validation).
    #[must_use]
    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "task_status_changed" => Some(Self::TaskStatusChanged),
            "task_priority_changed" => Some(Self::TaskPriorityChanged),
            "task_assigned" => Some(Self::TaskAssigned),
            _ => None,
        }
    }

    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::TaskStatusChanged => "task_status_changed",
            Self::TaskPriorityChanged => "task_priority_changed",
            Self::TaskAssigned => "task_assigned",
        }
    }

    /// All triggers, in stable order (used by selection queries).
    #[must_use]
    pub fn all() -> [Self; 3] {
        [
            Self::TaskStatusChanged,
            Self::TaskPriorityChanged,
            Self::TaskAssigned,
        ]
    }
}

/// The Phase 8B integration trigger vocabulary (Git events). These persist
