#[cfg(test)]
mod tests {
    use super::*;

    const USER_A: &str = "00000000-0000-0000-0000-00000000000a";
    const USER_B: &str = "00000000-0000-0000-0000-00000000000b";

    // -- trigger matrix ------------------------------------------------------

    #[test]
    fn assignment_matrix_matches_accepted_semantics() {
        // Created without assignee / no-op on both-missing: none.
        assert_eq!(assignment_delta(None, None), AssignmentDelta::NoOp);
        // Created with an initial assignee: emit (initial).
        assert_eq!(
            assignment_delta(None, Some(USER_A)),
            AssignmentDelta::Assigned { initial: true }
        );
        // Unassigned → assigned: emit.
        assert_eq!(
            assignment_delta(Some(USER_A), None).clone(),
            AssignmentDelta::Unassigned
        );
        // Assignee A → assignee B: emit (replacement).
        assert_eq!(
            assignment_delta(Some(USER_A), Some(USER_B)),
            AssignmentDelta::Assigned { initial: false }
        );
        // No-op reassignment to the same user: none.
        assert_eq!(
            assignment_delta(Some(USER_A), Some(USER_A)),
            AssignmentDelta::NoOp
        );
        // Assigned → unassigned: none.
        assert_eq!(
            assignment_delta(Some(USER_A), None),
            AssignmentDelta::Unassigned
        );
    }

    #[test]
    fn status_and_priority_changes_emit_only_on_actual_change() {
        assert!(!value_changed("todo", "todo"));
        assert!(value_changed("todo", "in_progress"));
        assert!(!value_changed("low", "low"));
        assert!(value_changed("low", "urgent"));
    }

    // -- loop prevention -----------------------------------------------------

    #[test]
    fn only_user_origin_events_are_evaluated() {
        assert!(should_evaluate(EventOrigin::User));
        assert!(!should_evaluate(EventOrigin::Automation));
    }

    #[test]
    fn integration_origin_events_are_evaluated_phase8b() {
        // Phase 8B policy amendment: integration-origin events participate
        // in Rules Evaluation (never impersonating users; provider logins
        // stay in the normalized payload).
        assert!(should_evaluate(EventOrigin::Integration));
    }

    #[test]
    fn integration_trigger_vocabulary_parses() {
        for trigger in [
            "git_push",
            "git_pull_request_opened",
            "git_pull_request_merged",
            "git_pull_request_closed",
            "git_branch_created",
            "git_branch_deleted",
            "git_release_published",
        ] {
            assert!(IntegrationTriggerType::parse(trigger).is_some(), "{trigger}");
            assert_eq!(
                IntegrationTriggerType::parse(trigger)
                    .expect("parse")
                    .as_str(),
                trigger
            );
        }
        assert!(IntegrationTriggerType::parse("github_pushed").is_none());
    }

    // -- event state serialization -------------------------------------------

    #[test]
    fn event_state_serializes_only_populated_fields() {
        let state = EventState {
            status: Some("todo"),
            ..EventState::default()
        };
        assert_eq!(
            state.to_json_str().expect("serializes"),
            "{\"status\":\"todo\"}"
        );
        let state = EventState {
            assignee_id: Some(USER_A.to_string()),
            ..EventState::default()
        };
        assert_eq!(
            state.to_json_str().expect("serializes"),
            "{\"assignee_id\":\"00000000-0000-0000-0000-00000000000a\"}"
        );
        assert_eq!(
            EventState::default().to_json_str().expect("serializes"),
            "{}"
        );
    }

    #[test]
    fn event_state_stays_within_cap() {
        let state = EventState {
            status: Some("in_progress"),
            priority: Some("urgent"),
            assignee_id: Some(USER_A.to_string()),
        };
        let json = state.to_json_str().expect("serializes");
        assert!(json.chars().count() <= limits::EVENT_STATE_JSON_MAX_CHARS);
    }

    // -- trigger vocabulary ---------------------------------------------------

    #[test]
    fn trigger_names_match_activity_vocabulary() {
        assert_eq!(
            TriggerType::TaskStatusChanged.as_str(),
            "task_status_changed"
        );
        assert_eq!(
            TriggerType::TaskPriorityChanged.as_str(),
            "task_priority_changed"
        );
        assert_eq!(TriggerType::TaskAssigned.as_str(), "task_assigned");
        assert_eq!(TriggerType::all().len(), 3);
    }
}
