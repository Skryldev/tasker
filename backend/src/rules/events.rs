/// Where an event came from. `Automation` events must carry their causing
/// execution id; they are never evaluated by rules (Phase 8B policy).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum EventOrigin {
    User,
    /// Events the Rules Engine itself produced. Never evaluated by rules
    /// (loop prevention); recorded for audit.
    Automation,
    /// Externally originated (Phase 8B: Git providers). Evaluated by rules
    /// (never impersonating a user); the provider login stays in the
    /// normalized payload as `external_actor` and never enters `users`.
    Integration,
}

impl EventOrigin {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::User => "user",
            Self::Automation => "automation",
            Self::Integration => "integration",
        }
    }
}

/// Trigger-relevant event state. Every field is optional; only the fields
/// relevant to the event's trigger type are populated. Enum values are
/// canonical (`&'static str` from the domain arrays); identifiers are
/// canonical UUID strings.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct EventState {
    pub status: Option<&'static str>,
    pub priority: Option<&'static str>,
    pub assignee_id: Option<String>,
}

impl EventState {
    /// Canonical compact JSON (only populated fields appear).
    #[must_use]
    pub fn to_json_value(&self) -> Value {
        let mut map = Map::new();
        if let Some(status) = self.status {
            map.insert("status".into(), Value::String(status.into()));
        }
        if let Some(priority) = self.priority {
            map.insert("priority".into(), Value::String(priority.into()));
        }
        if let Some(assignee_id) = &self.assignee_id {
            map.insert("assignee_id".into(), Value::String(assignee_id.clone()));
        }
        Value::Object(map)
    }

    /// Serialized form, bounded by
    /// [`limits::EVENT_STATE_JSON_MAX_CHARS`]. Event state only ever holds
    /// closed-domain enum values and UUIDs, so the cap cannot be exceeded by
    /// well-formed construction; the check is a defense-in-depth gate on the
    /// persistence path.
    pub fn to_json_str(&self) -> Result<String, RuleError> {
        let json = serde_json::to_string(&self.to_json_value())
            .expect("serializing EventState cannot fail");
        if json.chars().count() > limits::EVENT_STATE_JSON_MAX_CHARS {
            return Err(RuleError(vec![FieldError::new(
                "event_state",
                format!(
                    "event state JSON exceeds the maximum serialized size of {} characters",
                    limits::EVENT_STATE_JSON_MAX_CHARS
                ),
            )]));
        }
        Ok(json)
    }
}

/// A committed state change. Persistence lives in Task 3 (`engine.rs`); this
/// type is the pure domain record.
/// A committed state change. Persistence lives in Task 3 (`engine.rs`); this
/// type is the pure domain record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DomainEvent {
    /// `UUIDv7` identifier (unique per event).
    pub id: String,
    pub event_type: TriggerType,
    /// Event schema version; starts at 1 and bumps only with a
    /// breaking payload change.
    pub schema_version: u16,
    pub team_id: String,
    /// Historical identifier; deliberately NOT a foreign key to `tasks` so
    /// automation history survives task deletion.
    pub task_id: String,
    /// The human actor who caused the mutation, when applicable.
    pub actor_id: Option<String>,
    pub previous: EventState,
    pub new: EventState,
    pub origin: EventOrigin,
    /// Present on `Automation` events: the execution that caused them.
    pub causing_execution_id: Option<String>,
    /// Occurrence timestamp (epoch milliseconds, same clock as the repo).
    pub occurred_at: i64,
}

impl DomainEvent {
    pub const SCHEMA_VERSION: u16 = 1;
}

