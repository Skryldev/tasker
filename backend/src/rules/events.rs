//! Domain events, trigger semantics, and loop prevention for the Rules
//! Engine.
//!
//! A domain event records an actual committed state change. It is captured
//! inside the originating task-mutation transaction (Task 3) and consumed by
//! rule evaluation in the same transaction. Events carry only
//! trigger-relevant state — no descriptions, comments, credentials, or other
//! sensitive task content.
//!
//! **Trigger matrix** (the authoritative classification helpers are
//! [`assignment_delta`] and [`value_changed`]; Task 3 wires them to the real
//! mutation paths):
//!
//! | Mutation                                   | Event                 |
//! |--------------------------------------------|-----------------------|
//! | Task created with an initial assignee      | `task_assigned`       |
//! | Task created without an assignee           | none                  |
//! | Status change (transition endpoint)        | `task_status_changed` |
//! | Priority change (PATCH)                    | `task_priority_changed` |
//! | Unassigned → assigned                      | `task_assigned`       |
//! | Assignee A → assignee B                    | `task_assigned`       |
//! | Assigned → unassigned                      | none                  |
//! | Team-member removal auto-unassignment      | none                  |
//! | No-op update                               | none                  |
//!
//! **Loop prevention:** rules only evaluate events with origin
//! [`EventOrigin::User`] (see [`should_evaluate`]). In Phase 8A no internal
//! action mutates task state, so automation-origin events cannot arise; the
//! policy is nonetheless enforced at rule selection so any future trigger
//! (e.g. a comment trigger) inherits it. Automation-origin events still
//! carry `causing_execution_id` for audit. This deliberately ignores events
//! generated by *other* rules as well — a deterministic, conservative
//! policy; cross-rule automation can be enabled later by widening this one
//! function. It never suppresses legitimate independent user actions.

